// Compute centroid of polygon
function computeCentroid(coords) {
  let cx = 0, cy = 0;
  for (let i = 0; i < coords.length - 1; i++) {
    cx += coords[i][0];
    cy += coords[i][1];
  }
  const len = coords.length - 1;
  return [Number((cx / len).toFixed(4)), Number((cy / len).toFixed(4))];
}

